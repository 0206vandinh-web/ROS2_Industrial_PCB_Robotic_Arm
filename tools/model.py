def piece(kind,size,xyz,col,rot=(0,0,0),solid=True):return kind,size,xyz,col,rot,solid
def geom(parent,part,sdf):
 kind,size,pos,col,rot,solid=part;g=el(parent,'geometry')
 if kind=='box':dims={'size':txt(size)}
 elif kind=='cylinder':dims={'radius':size[0],'length':size[1]}
 else:dims={'radius':size[0]}
 if sdf:
  n=el(g,kind)
  for k,v in dims.items():el(n,k,v)
 else:el(g,kind,**dims)
def body(name,mass,dim,com,parts_,parent=None,xyz=(0,0,0),rpy=(0,0,0),typ='fixed',axis=(0,0,1),bounds=None):
 u=el(U,'link',name=name);s=el(M,'link',name=name);parts[name]=s
 jname='mount' if parent=='world' else ('j'+name[1:] if name.startswith('l') and name[1:].isdigit() else name+'_joint')
 el(s,'pose',txt((*xyz,*rpy)),relative_to=parent if parent!='world' else '__model__')
 ix,iy,iz=[mass*(dim[(i+1)%3]**2+dim[(i+2)%3]**2)/12 for i in range(3)]
 rows.append((name,mass,*com,ix,iy,iz))
 for node,is_s in [(u,False),(s,True)]:
  it=el(node,'inertial');I=dict(ixx=ix,iyy=iy,izz=iz,ixy=0,ixz=0,iyz=0)
  if is_s:
   el(it,'pose',txt((*com,0,0,0)));el(it,'mass',mass);ii=el(it,'inertia')
   for k,v in I.items():el(ii,k,v)
  else:el(it,'origin',xyz=txt(com));el(it,'mass',value=mass);el(it,'inertia',**I)
  for n,p in enumerate(parts_):
   for tag in (['visual','collision'] if p[-1] else ['visual']):
    obj=el(node,tag,name=f'{name}_{tag}_{n}')
    if is_s:el(obj,'pose',txt((*p[2],*p[4])))
    else:el(obj,'origin',xyz=txt(p[2]),rpy=txt(p[4]))
    geom(obj,p,is_s)
    if tag=='visual':
     mat=el(obj,'material') if is_s else el(obj,'material',name=f'{name}_{n}')
     if is_s:el(mat,'diffuse',p[3]);el(mat,'ambient',p[3])
     else:el(mat,'color',rgba=p[3])
    elif is_s:
     ode=el(el(el(obj,'surface'),'friction'),'ode');el(ode,'mu',.65);el(ode,'mu2',.65)
     if name in ('l3','l4','l5','l6'):
      el(el(obj.find('surface'),'contact'),'collide_bitmask',str(1<<(int(name[1:])-3)))
     sensor=el(s,'sensor',name=f'contact_{n}',type='contact');el(el(sensor,'contact'),'collision',obj.get('name'));el(sensor,'always_on','true')
 ju=el(U,'joint',name=jname,type=typ);el(ju,'origin',xyz=txt(xyz),rpy=txt(rpy));el(ju,'parent',link=parent);el(ju,'child',link=name)
 js=el(M,'joint',name=jname,type=typ);el(js,'parent',parent);el(js,'child',name)
 if bounds:
  ax=el(js,'axis');el(ax,'xyz',txt(axis));lim=el(ax,'limit');el(ju,'axis',xyz=txt(axis))
  nums=dict(zip(['lower','upper','effort','velocity'],bounds));el(ju,'limit',**nums)
  for k,v in nums.items():el(lim,k,v)
  for k,v in [('damping',.035),('friction',.008)]:el(ax.find('dynamics') if ax.find('dynamics') is not None else el(ax,'dynamics'),k,v)
  el(ju,'dynamics',damping=.035,friction=.008)
 return jname
